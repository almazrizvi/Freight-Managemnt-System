CREATE TABLE IF NOT EXISTS scheduler_job_definition (
    id UUID PRIMARY KEY,
    tenant_id VARCHAR(100) NOT NULL,
    job_name VARCHAR(150) NOT NULL,
    job_group VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    job_class_name VARCHAR(255) NOT NULL,
    cron_expression VARCHAR(120) NOT NULL,
    time_zone VARCHAR(100) NOT NULL DEFAULT 'UTC',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_paused BOOLEAN NOT NULL DEFAULT FALSE,
    misfire_policy VARCHAR(40) NOT NULL DEFAULT 'SMART_POLICY',
    payload_json TEXT,
    last_synced_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_scheduler_job_definition_tenant_group_name UNIQUE (tenant_id, job_group, job_name),
    CONSTRAINT chk_scheduler_job_definition_misfire_policy CHECK (
        misfire_policy IN ('SMART_POLICY', 'FIRE_ONCE_NOW', 'DO_NOTHING', 'IGNORE_MISFIRES')
    )
);

CREATE INDEX IF NOT EXISTS idx_scheduler_job_definition_tenant
    ON scheduler_job_definition (tenant_id);

CREATE INDEX IF NOT EXISTS idx_scheduler_job_definition_active
    ON scheduler_job_definition (is_active, is_paused);

CREATE TABLE IF NOT EXISTS QRTZ_JOB_DETAILS (
    SCHED_NAME VARCHAR(120) NOT NULL,
    JOB_NAME VARCHAR(200) NOT NULL,
    JOB_GROUP VARCHAR(200) NOT NULL,
    DESCRIPTION VARCHAR(250),
    JOB_CLASS_NAME VARCHAR(250) NOT NULL,
    IS_DURABLE BOOLEAN NOT NULL,
    IS_NONCONCURRENT BOOLEAN NOT NULL,
    IS_UPDATE_DATA BOOLEAN NOT NULL,
    REQUESTS_RECOVERY BOOLEAN NOT NULL,
    JOB_DATA BYTEA,
